import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const protocolRoot = path.resolve(__dirname, "../packages/protocol");
const manifestPath = path.resolve(protocolRoot, "schemas/manifest.json");
const targetFile = path.resolve(
  __dirname,
  "../packages/desktop-tauri/src-tauri/src/kernel/generated_types.rs",
);

if (!fs.existsSync(manifestPath)) {
  console.error("manifest.json not found. Run npm run export:schemas first.");
  process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));

function toPascalCase(str) {
  return str
    .replace(/[._\/-]([a-z0-9])/gi, (_, char) => char.toUpperCase())
    .replace(/^([a-z])/, (_, char) => char.toUpperCase());
}

function toSnakeCase(str) {
  return str
    .replace(/([A-Z])/g, "_$1")
    .toLowerCase()
    .replace(/^_/, "");
}

const RUST_KEYWORDS = new Set([
  "as",
  "break",
  "const",
  "continue",
  "crate",
  "else",
  "enum",
  "extern",
  "false",
  "fn",
  "for",
  "if",
  "impl",
  "in",
  "let",
  "loop",
  "match",
  "mod",
  "move",
  "mut",
  "pub",
  "ref",
  "return",
  "self",
  "Self",
  "static",
  "struct",
  "super",
  "trait",
  "true",
  "type",
  "unsafe",
  "use",
  "where",
  "while",
  "async",
  "await",
  "dyn",
]);

function rustFieldName(name) {
  const snake = toSnakeCase(name);
  if (RUST_KEYWORDS.has(snake)) {
    return `r#${snake}`;
  }
  return snake;
}

function mapPropertyType(prop) {
  if (!prop) return "serde_json::Value";
  if (prop.type === "string") return "String";
  if (prop.type === "boolean") return "bool";
  if (prop.type === "integer") return "i64";
  if (prop.type === "number") return "f64";
  if (prop.type === "array") {
    if (prop.items?.type === "string") return "Vec<String>";
    if (prop.items?.type === "integer") return "Vec<i64>";
    if (prop.items?.type === "boolean") return "Vec<bool>";
    return "Vec<serde_json::Value>";
  }
  return "serde_json::Value";
}

function generateVariant(typeTag, schemaFile, isOutbound = false) {
  const schemaPath = path.resolve(protocolRoot, "schemas", schemaFile);
  const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
  const variantName = toPascalCase(typeTag);
  const required = new Set(schema.required ?? []);
  const properties = schema.properties ?? {};

  const fields = [];
  for (const [propName, propDef] of Object.entries(properties)) {
    if (propName === "type") continue; // handled by serde(tag = "type")
    const isReq = required.has(propName);
    const rustType = mapPropertyType(propDef);
    const fieldName = rustFieldName(propName);

    const renameAttr = fieldName !== propName ? `    #[serde(rename = "${propName}")]\n` : "";
    if (isReq) {
      fields.push(`${renameAttr}    ${fieldName}: ${rustType},`);
    } else {
      fields.push(
        `${renameAttr}    #[serde(default, skip_serializing_if = "Option::is_none")]\n    ${fieldName}: Option<${rustType}>,`,
      );
    }
  }

  return {
    variantName,
    typeTag,
    code: `  #[serde(rename = "${typeTag}")]\n  ${variantName} {\n${fields.join("\n")}\n  },`,
  };
}

const inboundVariants = [];
for (const [typeTag, meta] of Object.entries(manifest.inbound)) {
  inboundVariants.push(generateVariant(typeTag, meta.file, false));
}

const outboundVariants = [];
for (const [typeTag, meta] of Object.entries(manifest.outbound)) {
  outboundVariants.push(generateVariant(typeTag, meta.file, true));
}

const rustCode = `// Auto-generated by scripts/generate-rust-protocol.mjs. DO NOT EDIT.
// Protocol Version: ${manifest.version}
// Generated At: ${manifest.generatedAt}

#![allow(non_camel_case_types)]
#![allow(clippy::large_enum_variant)]

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag = "type")]
pub enum SessionInboundMessage {
${inboundVariants.map((v) => v.code).join("\n\n")}
  #[serde(other)]
  Unknown,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag = "type")]
pub enum SessionOutboundMessage {
${outboundVariants.map((v) => v.code).join("\n\n")}
  #[serde(other)]
  Unknown,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct HandshakePayload {
    pub client_version: String,
    pub client_id: String,
}
`;

fs.writeFileSync(targetFile, rustCode, "utf8");
console.log(
  `[generate-rust-protocol] Generated ${inboundVariants.length} inbound and ${outboundVariants.length} outbound strongly-typed variants in: ${targetFile}`,
);
