import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const targetFile = path.resolve(
  __dirname,
  "../packages/desktop-tauri/src-tauri/src/kernel/generated_types.rs",
);

const header = `// Auto-generated by scripts/generate-rust-protocol.mjs. DO NOT EDIT.
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct HandshakePayload {
    pub client_version: String,
    pub client_id: String,
}
`;

fs.mkdirSync(path.dirname(targetFile), { recursive: true });
fs.writeFileSync(targetFile, header, "utf8");
console.log(`Generated Rust protocol types at: ${targetFile}`);
